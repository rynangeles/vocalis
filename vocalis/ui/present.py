def render_shell(settings: Settings, manager: ModelManager) -> str:
    """Sidebar identity. User content is escaped."""
    name = html.escape(settings.app_name)
    status = manager.get_status()
    provider = html.escape(status.provider.value)
    state = html.escape(status.state.value.replace("_", " "))
    if settings.model_provider is ModelProvider.MOCK:
        mode = "Development mode. Output is a simulated tone, not VoxCPM2 speech."
    else:
        mode = "Production provider. Speech is generated by VoxCPM2."
    return f"""
<section class="vocalis-shell">
  <div class="vocalis-brand">
    {_MARK}
    <div>
      <p class="vocalis-kicker">AI Voice Studio</p>
      <h1 class="vocalis-title">{name}</h1>
    </div>
  </div>
  <p class="vocalis-tagline">Give your words a voice.</p>
  <p class="vocalis-attribution">Powered by VoxCPM2</p>
  <p class="vocalis-mode">{html.escape(mode)}</p>
  <dl class="vocalis-status">
    <dt>Provider</dt>
    <dd>{provider}</dd>
    <dt>Engine</dt>
    <dd>{state}</dd>
  </dl>
</section>
""".strip()


def format_timestamp(value: datetime | None) -> str:
    if value is None:
        return "—"
    moment = value.astimezone(timezone.utc)
    return moment.strftime("%Y-%m-%d %H:%M:%S UTC")


def format_seconds(value: float | None) -> str:
    if value is None:
        return "—"
    return f"{value:.2f} s"


def truncate_text(value: str, limit: int = TEXT_PREVIEW_LIMIT) -> str:
    compact = " ".join(value.split())
    if len(compact) <= limit:
        return compact
    return compact[: limit - 1] + "…"


def status_label(state: JobState) -> str:
    return _STATUS_LABELS[state]


def type_label(generation_type: GenerationType) -> str:
    return _TYPE_LABELS[generation_type]


def output_kind(simulated: bool | None) -> str:
    if simulated is True:
        return "Simulated"
    if simulated is False:
        return "Real"
    return "—"


def playable_file(path: str | None) -> str | None:
    if not path:
        return None
    candidate = Path(path)
    if candidate.is_file():
        return str(candidate)
    return None


def format_job(job: GenerationJob) -> str:
    result = job.result
    provider = result.provider.value if result is not None else "—"
    lines = [
        f"Job ID: {job.id}",
        f"Type: {type_label(job.request.generation_type)}",
        f"Provider: {provider}",
        f"Status: {status_label(job.state)}",
        f"Created: {format_timestamp(job.created_at)}",
        f"Started: {format_timestamp(job.started_at)}",
        f"Completed: {format_timestamp(job.completed_at)}",
    ]
    if result is not None:
        lines.append(f"Generation time: {format_seconds(result.generation_seconds)}")
        lines.append(f"Audio length: {format_seconds(result.audio.duration_seconds)}")
        lines.append(f"Output: {output_kind(result.simulated)}")
        lines.append(result.message)
        if result.simulated:
            lines.append(result.audio.disclaimer)
        if playable_file(str(result.output_path)) is None:
            lines.append("The output file is no longer available.")
    elif job.state is JobState.FAILED and job.error_message:
        lines.append(f"Error: {job.error_message}")
    elif job.state is JobState.CANCELLED:
        lines.append(job.error_message or "Cancelled before it started.")
    elif job.state in {JobState.QUEUED, JobState.RUNNING}:
        lines.append("Waiting for the worker. Progress is not reported.")
    return "\n".join(lines)


def format_record(record: GenerationRecord) -> str:
    lines = [
        f"Job ID: {record.id}",
        f"Type: {type_label(record.generation_type)}",
        f"Provider: {record.provider.value}",
        f"Status: {status_label(record.status)}",
        f"Created: {format_timestamp(record.created_at)}",
        f"Started: {format_timestamp(record.started_at)}",
        f"Completed: {format_timestamp(record.completed_at)}",
        f"Generation time: {format_seconds(record.generation_seconds)}",
        f"Audio length: {format_seconds(record.duration_seconds)}",
        f"Output: {output_kind(record.simulated)}",
        "",
        "Text:",
        record.input_text,
    ]
    if record.voice_description:
        lines.extend(["", "Voice description:", record.voice_description])
    if record.reference_transcript:
        lines.extend(["", "Reference transcript:", record.reference_transcript])
    if record.audio_disclaimer:
        lines.extend(["", record.audio_disclaimer])
    if record.error_message:
        lines.extend(["", f"Error: {record.error_message}"])
    if record.output_audio_path and playable_file(record.output_audio_path) is None:
        lines.append("The output file is no longer available.")
    if record.simulated is True:
        lines.append("This result is simulated. It is not VoxCPM2 speech.")
    return "\n".join(lines)


def history_row(record: GenerationRecord) -> list[str]:
    return [
        format_timestamp(record.created_at),
        type_label(record.generation_type),
        truncate_text(record.input_text),
        record.provider.value,
        status_label(record.status),
        format_seconds(record.duration_seconds if record.duration_seconds is not None else record.generation_seconds),
        output_kind(record.simulated),
    ]


def format_inspection(inspection: AudioInspection) -> str:
    duration = format_seconds(inspection.duration_seconds) if inspection.duration_measured else "unavailable"
    return "\n".join(
        [
            f"Format: {inspection.audio_format.upper()}",
            f"Sample rate: {inspection.sample_rate if inspection.sample_rate is not None else '—'}",
            f"Channels: {inspection.channels if inspection.channels is not None else '—'}",
            f"Duration: {duration}",
            f"Size: {inspection.size_bytes} bytes",
            inspection.note,
            "The reference file is only read. Mock mode does not use it to clone a voice.",
        ]
    )


def parse_type_filter(label: str | None) -> GenerationType | None:
    if not label or label == "Any type":
        return None
    return _TYPE_BY_LABEL.get(label)


def parse_status_filter(label: str | None) -> JobState | None:
    if not label or label == "Any status":
        return None
    return _STATUS_BY_LABEL.get(label)


def parse_provider_filter(label: str | None) -> ModelProvider | None:
    if not label or label == "Any provider":
        return None
    return _PROVIDER_BY_LABEL.get(label)


def format_bytes(count: int) -> str:
    mebibyte = 1024 * 1024
    gibibyte = 1024 * mebibyte
    if count >= gibibyte:
        return f"{count / gibibyte:.1f} GiB"
    if count >= mebibyte:
        if count % mebibyte == 0:
            return f"{count // mebibyte} MiB"
        return f"{count / mebibyte:.1f} MiB"
    return f"{count} bytes"


def format_uptime(seconds: float) -> str:
    total = max(0, int(seconds))
    hours, remainder = divmod(total, 3600)
    minutes, secs = divmod(remainder, 60)
    return f"{hours}h {minutes}m {secs}s"


def render_settings(settings: Settings, manager: ModelManager, queue: GenerationQueue, database_available: bool) -> str:
    status = manager.get_status()
    capabilities = manager.capabilities
    sample_rate = "—" if capabilities.sample_rate is None else str(capabilities.sample_rate)
    inference = "Simulated tones" if not capabilities.real_inference else "Real inference"
    database = "Available" if database_available else "Unavailable"
    return "\n".join(
        [
            "Settings are read from the environment. This page does not change them.",
            "",
            f"Application: {settings.app_name}",
            "Version: Not set",
            f"Environment: {settings.app_env.value}",
            f"Provider: {settings.model_provider.value}",
            f"Engine: {status.state.value}",
            f"Engine detail: {status.message}",
            f"Inference: {inference}",
            f"Maximum concurrent generations: {settings.max_concurrent_generations}",
            f"Pending queue limit: {settings.max_queue_size}",
            f"Maximum upload size: {format_bytes(settings.max_upload_bytes)}",
            f"Sample rate: {sample_rate}",
            "Output format: WAV",
            f"History database: {database}",
            f"Queue accepting jobs: {'yes' if queue.snapshot().accepting else 'no'}",
        ]
    )


def render_monitor(
    settings: Settings,
    manager: ModelManager,
    queue: GenerationQueue,
    *,
    uptime_seconds: float,
    cpu_percent: float | None,
    memory_percent: float | None,
    memory_used_bytes: int | None,
    memory_total_bytes: int | None,
    database_available: bool,
) -> str:
    snapshot: QueueSnapshot = queue.snapshot()
    status = manager.get_status()
    cpu = "Unavailable" if cpu_percent is None else f"{cpu_percent:.0f}%"
    if memory_percent is None or memory_used_bytes is None or memory_total_bytes is None:
        memory = "Unavailable"
    else:
        memory = (
            f"{memory_percent:.0f}% "
            f"({format_bytes(memory_used_bytes)} of {format_bytes(memory_total_bytes)})"
        )
    directories = "Ready" if settings.design_output_dir.is_dir() and settings.reference_upload_dir.is_dir() else "Missing"
    return "\n".join(
        [
            f"Uptime: {format_uptime(uptime_seconds)}",
            f"CPU: {cpu}",
            f"Memory: {memory}",
            f"Provider: {settings.model_provider.value}",
            f"Engine: {status.state.value}",
            f"Engine detail: {status.message}",
            f"Queue accepting jobs: {'yes' if snapshot.accepting else 'no'}",
            f"Pending jobs: {snapshot.pending_count}",
            f"Running: {'yes' if snapshot.running else 'no'}",
            f"Pending limit: {snapshot.max_pending}",
            f"History database: {'Available' if database_available else 'Unavailable'}",
            f"Output and upload directories: {directories}",
            "GPU monitoring is not configured.",
        ]
    )
