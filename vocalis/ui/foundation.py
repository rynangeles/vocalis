"""Shared studio identity used by the shell and the startup checks."""

from __future__ import annotations

import html

from vocalis.core.config import Settings
from vocalis.core.types import ModelProvider
from vocalis.ui.present import _MARK


def render_foundation(settings: Settings) -> str:
    """Return the studio identity block."""
    name = html.escape(settings.app_name)
    provider = html.escape(settings.model_provider.value)
    if settings.model_provider is ModelProvider.MOCK:
        mode = "Development mode. Output is a simulated tone, not VoxCPM2 speech."
    else:
        mode = "Production provider. Speech is generated by VoxCPM2."
    return f"""
<section class="vocalis-shell">
  <div class="vocalis-brand">
    {_MARK}
    <div>
      <p class="vocalis-kicker">AI Voice Studio</p>
      <h1 class="vocalis-title">{name}</h1>
    </div>
  </div>
  <p class="vocalis-tagline">Give your words a voice.</p>
  <p class="vocalis-attribution">Powered by VoxCPM2</p>
  <p class="vocalis-mode">{html.escape(mode)}</p>
  <dl class="vocalis-status">
    <dt>Provider</dt>
    <dd>{provider}</dd>
  </dl>
</section>
""".strip()


def display_address(settings: Settings) -> str:
    host = settings.app_host
    if ":" in host:
        host = f"[{host}]"
    return f"http://{host}:{settings.app_port}"
